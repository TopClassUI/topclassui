import { Table } from 'topclassui/table'
import { getLabels } from 'topclassui/labels/get-labels'

import type { Locale } from '../../content/pages'
import { GUIDES } from '../../lib/data'
import { familyOf, scaleEndsOf } from '../../lib/utility-row'
import { PROSE_COLUMN, PROSE_TABLE, TABLE_CODE } from '../classes'

type Row = (typeof GUIDES.utilities)[number]

function Code({ children }: { children: string }) {
  return <code dir="ltr" className={TABLE_CODE}>{children}</code>
}

function Tokens({ values, through }: { values: readonly string[]; through: string }) {
  const ends = scaleEndsOf(values)
  return ends === null ? <Code>{familyOf(values)}</Code> : <span><Code>{ends[0]}</Code> {through} <Code>{ends[1]}</Code></span>
}

function Utilities({ values, through }: { values: readonly string[]; through: string }) {
  const ends = scaleEndsOf(values)
  if (ends !== null) return <span><Code>{ends[0]}</Code> {through} <Code>{ends[1]}</Code></span>
  return <span className="flex flex-wrap gap-x-2 gap-y-1">{values.map((value) => <Code key={value}>{value}</Code>)}</span>
}

/** The `@theme inline` block of the library's styles.css as Token | Utilities, generated by docs:data (docs-site page 4). */
export function ThemeUtilities({ locale, labels }: { locale: Locale; labels: { token: string; utilities: string; through: string } }) {
  return (
    <Table
      {...getLabels(locale)}
      items={GUIDES.utilities}
      getKey={(row: Row) => row.tokens.join(' ')}
      caption={`${labels.token}, ${labels.utilities}`}
      className={PROSE_TABLE}
      columns={[
        // The frame gives Token 348 of its 944 px.
        { key: 'token', header: labels.token, rowHeader: true, className: `${PROSE_COLUMN.wrap} w-[37%]`, cell: (row: Row) => <Tokens values={row.tokens} through={labels.through} /> },
        { key: 'utilities', header: labels.utilities, className: PROSE_COLUMN.prose, cell: (row: Row) => <Utilities values={row.utilities} through={labels.through} /> },
      ]}
    />
  )
}
