import { Table } from 'topclassui/table'
import { getLabels } from 'topclassui/labels/get-labels'

import type { Locale } from '../../content/pages'
import { GUIDES } from '../../lib/data'
import { familyOf, groupedRows, scaleEndsOf, type UtilityRow } from '../../lib/utility-row'
import { PROSE_COLUMN, PROSE_TABLE } from '../classes'

// The frame sets the token names as the cell's plain muted text and the utilities as 10.5 px code in the body colour.
const VALUE = 'font-mono text-[0.6875rem] text-body'

function Code({ children }: { children: string }) {
  return <code dir="ltr" className={VALUE}>{children}</code>
}

function Tokens({ row, through, scale }: { row: UtilityRow; through: string; scale: string }) {
  const ends = scaleEndsOf(row.tokens)
  if (ends !== null) return <span dir="ltr">{ends[0]} {through} {ends[1]}</span>
  if (row.scale) return <span>{scale}</span>
  if (row.tones !== null) return <span dir="ltr" className="whitespace-nowrap">{`${row.tokens[0]?.replace(/-[^-]+$/, '-*') ?? ''}: ${row.tones.join(', ')}`}</span>
  return <span dir="ltr">{familyOf(row.tokens)}</span>
}

function Utilities({ values, through }: { values: readonly string[]; through: string }) {
  const ends = scaleEndsOf(values)
  if (ends !== null) return <span><Code>{ends[0]}</Code> {through} <Code>{ends[1]}</Code></span>
  return <span className="flex flex-wrap gap-x-2 gap-y-1">{values.map((value) => <Code key={value}>{value}</Code>)}</span>
}

/** The `@theme inline` block of the library's styles.css as Token | Utilities, generated by docs:data and grouped as the frame draws it (docs-site page 4). */
export function ThemeUtilities({ locale, labels }: { locale: Locale; labels: { token: string; utilities: string; through: string; scale: string } }) {
  const rows = groupedRows(GUIDES.utilities)
  return (
    <Table
      {...getLabels(locale)}
      items={rows}
      getKey={(row: UtilityRow) => row.tokens.join(' ')}
      caption={`${labels.token}, ${labels.utilities}`}
      visibleRows={rows.length}
      className={PROSE_TABLE}
      columns={[
        // The frame gives Token 348 of its 944 px.
        { key: 'token', header: labels.token, rowHeader: true, className: `${PROSE_COLUMN.wrap} w-[37%]`, cell: (row: UtilityRow) => <Tokens row={row} through={labels.through} scale={labels.scale} /> },
        { key: 'utilities', header: labels.utilities, className: PROSE_COLUMN.prose, cell: (row: UtilityRow) => <Utilities values={row.utilities} through={labels.through} /> },
      ]}
    />
  )
}
