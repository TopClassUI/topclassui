// pnpm icons:build regenerates src/icons from raw/. --check fails instead of writing.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

import { generate, type IconSource } from './lib/icons.js'

const ROOT = process.cwd()
const RAW = join(ROOT, 'raw')
const OUT = join(ROOT, 'src', 'icons')
const DOCS = join(ROOT, 'docs', 'icons.md')
const check = process.argv.includes('--check')

if (!existsSync(RAW)) {
  console.error('icons-build: raw/ does not exist; it is the allow-list of icons to build')
  process.exit(1)
}

const sources: IconSource[] = readdirSync(RAW)
  .filter((f) => f.endsWith('.svg'))
  .map((f) => ({ name: f.slice(0, -4), svg: readFileSync(join(RAW, f), 'utf8') }))

let files: Map<string, string>
try {
  files = generate(sources, readFileSync(DOCS, 'utf8'))
} catch (error) {
  console.error(`icons-build: ${error instanceof Error ? error.message : String(error)}`)
  process.exit(1)
}

if (check) {
  const wrong: string[] = []
  for (const [rel, content] of files) {
    const file = join(OUT, rel)
    if (!existsSync(file) || readFileSync(file, 'utf8') !== content) wrong.push(rel)
  }
  const dataDir = join(OUT, 'data')
  const orphans = existsSync(dataDir)
    ? readdirSync(dataDir).filter((f) => f.endsWith('.ts') && !files.has(`data/${f}`))
    : []
  for (const o of orphans) wrong.push(`data/${o} (no longer in raw/)`)

  // A generated module the pipeline no longer owns would otherwise linger forever.
  const stray = readdirSync(OUT)
    .filter((f) => f.endsWith('.generated.ts') && !files.has(f))
  for (const f of stray) wrong.push(`${f} (not generated by the pipeline)`)

  if (wrong.length) {
    console.error(`icons-build: ${String(wrong.length)} generated file(s) do not match raw/:`)
    for (const w of wrong) console.error(`  ${w}`)
    console.error('\nRun pnpm icons:build.')
    process.exit(1)
  }
  console.log(`icons-build: ok, ${String(sources.length)} icons match raw/`)
  process.exit(0)
}

// Dropped wholesale, so an icon removed from raw/ cannot linger in the bundle.
if (existsSync(join(OUT, 'data'))) rmSync(join(OUT, 'data'), { recursive: true })

for (const [rel, content] of files) {
  const file = join(OUT, rel)
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, content, { encoding: 'utf8' })
}

const written = [...files.keys()].filter((k) => k.startsWith('data/')).length
console.log(
  `icons-build: wrote ${String(written)} icons and ${String(files.size - written)} generated modules`,
)
